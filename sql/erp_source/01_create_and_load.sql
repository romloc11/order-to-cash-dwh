/*
 * ERP source (SAP-shaped), simulated.
 *
 * In production the warehouse would read these tables from the ERP replica through
 * a linked server. Here they live in the same SQL Server instance, in their own
 * database, so the rest of the pipeline reads them exactly as it would a remote
 * source: only through SELECT, never through shared objects.
 *
 * Column names and types follow SAP: dates are CHAR(8) 'YYYYMMDD', keys are
 * zero-padded strings, amounts are unsigned with a debit/credit flag (SHKZG).
 * Blank values arrive as NULL from the CSV load; silver treats NULL and '' alike.
 *
 * Re-runnable: drops and recreates the tables.
 */
IF DB_ID('erp_source') IS NULL
    CREATE DATABASE erp_source;
GO
USE erp_source;
GO

DROP TABLE IF EXISTS dbo.CDPOS, dbo.CDHDR, dbo.VBRK, dbo.BSAD, dbo.BSID,
                     dbo.T171T, dbo.T052, dbo.PA0001, dbo.KNVP, dbo.KNKK, dbo.KNVV, dbo.KNA1;
GO

CREATE TABLE dbo.KNA1 (               -- customer master, general data
    MANDT CHAR(3) NOT NULL, KUNNR CHAR(10) NOT NULL, NAME1 NVARCHAR(60), STCD1 VARCHAR(16),
    KTOKD CHAR(4), LAND1 CHAR(2), ORT01 NVARCHAR(40), ERDAT CHAR(8),
    CONSTRAINT PK_KNA1 PRIMARY KEY (MANDT, KUNNR));

CREATE TABLE dbo.KNVV (               -- customer master, sales area data
    MANDT CHAR(3) NOT NULL, KUNNR CHAR(10) NOT NULL, VKORG CHAR(4) NOT NULL, VTWEG CHAR(2) NOT NULL,
    SPART CHAR(2) NOT NULL, BZIRK CHAR(6), ZTERM CHAR(4),
    CONSTRAINT PK_KNVV PRIMARY KEY (MANDT, KUNNR, VKORG, VTWEG, SPART));

CREATE TABLE dbo.KNKK (               -- customer credit management
    MANDT CHAR(3) NOT NULL, KUNNR CHAR(10) NOT NULL, KKBER CHAR(4) NOT NULL, KLIMK DECIMAL(15,2),
    CRBLB CHAR(1), CTLPC CHAR(3),
    CONSTRAINT PK_KNKK PRIMARY KEY (MANDT, KUNNR, KKBER));

CREATE TABLE dbo.KNVP (               -- customer partner functions (CO = collector)
    MANDT CHAR(3) NOT NULL, KUNNR CHAR(10) NOT NULL, VKORG CHAR(4) NOT NULL, VTWEG CHAR(2) NOT NULL,
    SPART CHAR(2) NOT NULL, PARVW CHAR(2) NOT NULL, PARZA CHAR(3) NOT NULL, PERNR CHAR(8),
    CONSTRAINT PK_KNVP PRIMARY KEY (MANDT, KUNNR, VKORG, VTWEG, SPART, PARVW, PARZA));

CREATE TABLE dbo.PA0001 (PERNR CHAR(8) NOT NULL PRIMARY KEY, ENAME NVARCHAR(40));      -- employees
CREATE TABLE dbo.T052   (ZTERM CHAR(4) NOT NULL PRIMARY KEY, ZTAG1 INT, [TEXT] NVARCHAR(40)); -- payment terms
CREATE TABLE dbo.T171T  (BZIRK CHAR(6) NOT NULL PRIMARY KEY, BZTXT NVARCHAR(40));      -- sales districts

CREATE TABLE dbo.BSID (               -- open customer items
    MANDT CHAR(3) NOT NULL, BUKRS CHAR(4) NOT NULL, KUNNR CHAR(10) NOT NULL, GJAHR CHAR(4) NOT NULL,
    BELNR CHAR(10) NOT NULL, BUZEI CHAR(3) NOT NULL, BUDAT CHAR(8), BLDAT CHAR(8), BLART CHAR(2),
    SHKZG CHAR(1), DMBTR DECIMAL(15,2), WAERS CHAR(3), ZFBDT CHAR(8), ZBD1T INT, XBLNR VARCHAR(16),
    VBELN CHAR(10), ZTERM CHAR(4),
    CONSTRAINT PK_BSID PRIMARY KEY (MANDT, BUKRS, KUNNR, GJAHR, BELNR, BUZEI));

CREATE TABLE dbo.BSAD (               -- cleared customer items
    MANDT CHAR(3) NOT NULL, BUKRS CHAR(4) NOT NULL, KUNNR CHAR(10) NOT NULL, GJAHR CHAR(4) NOT NULL,
    BELNR CHAR(10) NOT NULL, BUZEI CHAR(3) NOT NULL, BUDAT CHAR(8), BLDAT CHAR(8), BLART CHAR(2),
    SHKZG CHAR(1), DMBTR DECIMAL(15,2), WAERS CHAR(3), ZFBDT CHAR(8), ZBD1T INT, XBLNR VARCHAR(16),
    VBELN CHAR(10), ZTERM CHAR(4), AUGDT CHAR(8), AUGBL CHAR(10),
    CONSTRAINT PK_BSAD PRIMARY KEY (MANDT, BUKRS, KUNNR, GJAHR, BELNR, BUZEI));
CREATE INDEX IX_BSAD_AUGBL ON dbo.BSAD (AUGBL) INCLUDE (KUNNR, BLART, SHKZG, DMBTR);

CREATE TABLE dbo.VBRK (               -- billing document header
    MANDT CHAR(3) NOT NULL, VBELN CHAR(10) NOT NULL, FKART CHAR(4), FKDAT CHAR(8), KUNAG CHAR(10),
    NETWR DECIMAL(15,2), WAERS CHAR(3),
    CONSTRAINT PK_VBRK PRIMARY KEY (MANDT, VBELN));

CREATE TABLE dbo.CDHDR (              -- change document header
    MANDANT CHAR(3) NOT NULL, OBJECTCLAS CHAR(15) NOT NULL, OBJECTID CHAR(90) NOT NULL,
    CHANGENR CHAR(10) NOT NULL, USERNAME CHAR(12), UDATE CHAR(8), UTIME CHAR(6), TCODE CHAR(20),
    CONSTRAINT PK_CDHDR PRIMARY KEY (MANDANT, OBJECTCLAS, OBJECTID, CHANGENR));

CREATE TABLE dbo.CDPOS (              -- change document items
    MANDANT CHAR(3) NOT NULL, OBJECTCLAS CHAR(15) NOT NULL, OBJECTID CHAR(90) NOT NULL,
    CHANGENR CHAR(10) NOT NULL, TABNAME CHAR(30) NOT NULL, TABKEY CHAR(70), FNAME CHAR(30) NOT NULL,
    CHNGIND CHAR(1), VALUE_NEW VARCHAR(40), VALUE_OLD VARCHAR(40),
    CONSTRAINT PK_CDPOS PRIMARY KEY (MANDANT, OBJECTCLAS, OBJECTID, CHANGENR, TABNAME, FNAME));
GO

